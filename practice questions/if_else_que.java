import java.util.*;

public class if_else_que {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();

        if (n > 100) {
            System.out.println("Big");
        }
        
        System.out.println("Number");
    }    
}


/*You are given a number n, you have to use the if statement to print "Big" 
 if the given number is greater than 100. The statement "Number" be printed regardless. */